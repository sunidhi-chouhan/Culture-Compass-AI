#!/usr/bin/env npx tsx
/**
 * Phase 7 — Schedule Quality Score eval runner.
 *
 * Baseline: mock day-wise itinerary (or seeded bad schedule for E09).
 * Final: TripMate mock analyze → apply actionable suggestions.
 *
 * Usage (from apps/web):
 *   pnpm eval:schedule
 *   npx tsx scripts/run-schedule-eval.ts
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  formatEvalBreakdownMarkdown,
  formatEvalMarkdownTable,
  runAllEvalCases,
} from "../lib/eval/run-eval";
import { SQS_WEIGHTS } from "../lib/eval/schedule-quality-score";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoDocs = join(__dirname, "../../../docs/eval");

const results = runAllEvalCases();
const table = formatEvalMarkdownTable(results);
const breakdown = formatEvalBreakdownMarkdown(results);
const e09 = results.find((r) => r.id === "E09");
const e10 = results.find((r) => r.id === "E10");

const doc = `# Schedule Quality Score — Eval Results

Generated by \`apps/web/scripts/run-schedule-eval.ts\` (Phase 7).

## Metric

**Schedule Quality Score (SQS)** = 0–100, deterministic rubric:

| Dimension | Weight | Good means |
|---|---:|---|
| Realism / conflicts | ${SQS_WEIGHTS.realism} | No impossible overlaps; sane buffers; meals/rest |
| Cultural fit | ${SQS_WEIGHTS.culturalFit} | Stops align with stated interests |
| Completeness | ${SQS_WEIGHTS.completeness} | Expected days + morning/afternoon/evening balance |
| Actionability | ${SQS_WEIGHTS.actionability} | Specific places, not vague filler |

## Baseline vs final

| Path | What runs |
|---|---|
| **Baseline** | Challenged single-shot mock itinerary (tight buffers / long stops), or seeded bad Rome schedule for E09 |
| **+ TripMate** | Mock TripMate analyze → apply **conflict** and **pacing** repair suggestions |

Same 10 cases (E01–E10) for both paths. Cultural add-on suggestions are available in product UX but excluded from the scored repair path so SQS measures schedule realism fixes.

## Results table

${table}

## Dimension breakdown (baseline → improved)

${breakdown}

## Human-review notes (challenging cases)

### E09 — Existing bad schedule (Rome)
- Seed: three major museums stacked in one morning with 5–8 min buffers, overlapping clock times, no lunch.
- Baseline SQS: **${e09?.baseline.score ?? "—"}**
- +TripMate SQS: **${e09?.improved.score ?? "—"}** (Δ ${e09 ? (e09.delta >= 0 ? "+" : "") + e09.delta : "—"})
- Applied suggestions: **${e09?.appliedSuggestions ?? 0}**
- Review: TripMate should widen buffers / reorder / shorten overload. Score movement is the primary evidence; spot-check that post-apply travel buffers are ≥15 where flagged.

### E10 — Lesser-known Indore
- Baseline SQS: **${e10?.baseline.score ?? "—"}**
- +TripMate SQS: **${e10?.improved.score ?? "—"}** (Δ ${e10 ? (e10.delta >= 0 ? "+" : "") + e10.delta : "—"})
- Review: Prefer grounded, specific stops over invented landmarks. Actionability dimension penalizes vague filler; cultural fit rewards food/festival alignment.

## Reproduce

\`\`\`bash
cd apps/web
pnpm eval:schedule
\`\`\`

Writes this file under \`docs/eval/schedule-quality-results.md\`.
`;

mkdirSync(repoDocs, { recursive: true });
const outPath = join(repoDocs, "schedule-quality-results.md");
writeFileSync(outPath, doc, "utf8");

console.log(table);
console.log(`\nWrote ${outPath}`);
